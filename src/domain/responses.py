"""
Domain models for AI-generated responses.

This module defines the data structures for responses generated by the LLM.
A Response is an auditable artifact that links the generated answer back to
the query, stores supporting citations, and tracks generation metadata.
"""
import uuid
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, ConfigDict, Field


# -----------------------------------------------------------------------------
# Enums
# -----------------------------------------------------------------------------

class ResponseStatus(str, Enum):
    """Tracks the lifecycle of the response generation."""
    PENDING = "pending"
    GENERATING = "generating"
    COMPLETED = "completed"
    FAILED = "failed"
    NO_ANSWER = "no_answer"


class ResponseConfidence(str, Enum):
    """Overall confidence level in the entire response."""
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    UNCERTAIN = "uncertain"


# -----------------------------------------------------------------------------
# Domain Models
# -----------------------------------------------------------------------------

class Response(BaseModel):
    """
    Represents an AI-generated response to a user query.

    This model is an auditable artifact that tracks the generated answer,
    supporting citations, LLM model used, token consumption, and generation metadata.
    """
    model_config = ConfigDict(
        from_attributes=True,
        use_enum_values=True,
    )

    id: uuid.UUID = Field(default_factory=uuid.uuid4, description="Unique identifier for this response.")
    query_id: uuid.UUID = Field(..., description="Links back to the user's query.")
    conversation_id: Optional[uuid.UUID] = Field(default=None, description="Links to the broader conversation thread.")

    answer_text: Optional[str] = Field(default=None, description="The generated Arabic answer.")
    status: ResponseStatus = Field(default=ResponseStatus.PENDING, description="Current state of the response.")
    confidence: ResponseConfidence = Field(default=ResponseConfidence.UNCERTAIN, description="Overall confidence level in the response.")

    model_name: Optional[str] = Field(default=None, description="Which LLM was used (e.g., 'gpt-4', 'llama-3-70b').")
    model_version: Optional[str] = Field(default=None, description="Specific model version or commit hash.")

    prompt_tokens: int = Field(default=0, ge=0, description="Number of tokens in the prompt sent to LLM.")
    completion_tokens: int = Field(default=0, ge=0, description="Number of tokens in the generated answer.")
    total_tokens: int = Field(default=0, ge=0, description="Total tokens consumed (prompt + completion).")
    generation_time_ms: Optional[int] = Field(default=None, ge=0, description="How long generation took in milliseconds.")

    temperature: Optional[float] = Field(default=None, ge=0.0, le=2.0, description="LLM temperature setting used.")

    metadata: Dict[str, Any] = Field(default_factory=dict, description="Extra data (e.g., retrieval scores, prompt template used).")
    created_at: datetime = Field(default_factory=datetime.utcnow, description="Timestamp when the response was initiated.")
    completed_at: Optional[datetime] = Field(default=None, description="Timestamp when the response was completed.")

    def is_complete(self) -> bool:
        return self.status == ResponseStatus.COMPLETED

    def has_answer(self) -> bool:
        return bool(self.answer_text) and self.answer_text.strip() != ""

    def get_token_cost_estimate(self, cost_per_1k_tokens: float) -> float:
        return (self.total_tokens / 1000.0) * cost_per_1k_tokens

    def mark_completed(
        self,
        answer: str,
        prompt_tokens: int,
        completion_tokens: int,
        model_name: str,
        generation_time_ms: Optional[int] = None,
        confidence: ResponseConfidence = ResponseConfidence.MEDIUM,
    ) -> None:
        self.answer_text = answer
        self.status = ResponseStatus.COMPLETED
        self.prompt_tokens = prompt_tokens
        self.completion_tokens = completion_tokens
        self.total_tokens = prompt_tokens + completion_tokens
        self.model_name = model_name
        self.generation_time_ms = generation_time_ms
        self.confidence = confidence
        self.completed_at = datetime.utcnow()

    def mark_failed(self, error: str) -> None:
        self.status = ResponseStatus.FAILED
        self.completed_at = datetime.utcnow()
        if "errors" not in self.metadata:
            self.metadata["errors"] = []
        self.metadata["errors"].append({
            "error": error,
            "timestamp": datetime.utcnow().isoformat(),
        })

    def mark_no_answer(self, reason: str = "No relevant information found") -> None:
        self.status = ResponseStatus.NO_ANSWER
        self.completed_at = datetime.utcnow()
        self.metadata["no_answer_reason"] = reason


# -----------------------------------------------------------------------------
# LLM Generation Contracts (Used by LLM Providers and Generation Phase)
# -----------------------------------------------------------------------------

class GenerationRequest(BaseModel):
    """Request payload for LLM providers.
    
    Supports two modes:
    1. Legacy: system_prompt + user_prompt (single-turn)
    2. Messages: full conversation history (multi-turn with memory)
    
    Providers should call request.get_messages() to get the canonical format.
    """
    system_prompt: str
    user_prompt: str
    messages: Optional[List[Dict[str, str]]] = None  # NEW: full conversation
    temperature: Optional[float] = None
    max_tokens: Optional[int] = None

    def get_messages(self) -> List[Dict[str, str]]:
        """Return the messages list, building from system+user if not provided.
        
        This provides backward compatibility: providers that don't yet use
        the messages field will still work with the legacy system/user prompts.
        """
        if self.messages:
            return self.messages
        return [
            {"role": "system", "content": self.system_prompt},
            {"role": "user", "content": self.user_prompt},
        ]


class GenerationResponse(BaseModel):
    """Response payload from LLM providers."""
    content: str
    provider: str
    model: str
    tokens_used: int = 0
    latency_ms: float = 0.0
    metadata: Dict[str, Any] = Field(default_factory=dict)